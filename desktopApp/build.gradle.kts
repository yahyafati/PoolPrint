import org.jetbrains.compose.desktop.application.dsl.TargetFormat

plugins {
    alias(libs.plugins.kotlinJvm)
    alias(libs.plugins.composeMultiplatform)
    alias(libs.plugins.composeCompiler)
}

// One version for both apps, from gradle.properties (docs/release.md, Phase 2; buildSrc/PoolPrintVersion.kt).
val appVersion = PoolPrintVersion.from(providers)

// The full version name (with -rc.N) for Settings → About, as a generated BuildInfo.kt. A source file rather than a
// JVM argument, so it is also there under `run` and `hotRun`.
val generateBuildInfo = tasks.register("generateBuildInfo") {
    val versionName = appVersion.name
    val outputDir = layout.buildDirectory.dir("generated/buildInfo/kotlin")
    inputs.property("versionName", versionName)
    outputs.dir(outputDir)
    doLast {
        val file = outputDir.get().file("com/yahyafati/poolprint/BuildInfo.kt").asFile
        file.parentFile.mkdirs()
        // versionName is checked against a strict pattern (PoolPrintVersion), so it is safe in a string literal.
        file.writeText(
            """
            |// Generated by :desktopApp:generateBuildInfo from gradle.properties. Do not edit.
            |package com.yahyafati.poolprint
            |
            |internal object BuildInfo {
            |    const val VERSION_NAME: String = "$versionName"
            |}
            |""".trimMargin(),
        )
    }
}
kotlin.sourceSets.main {
    kotlin.srcDir(generateBuildInfo)
}

dependencies {
    implementation(project(":shared"))

    implementation(compose.desktop.currentOs)
    implementation(libs.kotlinx.coroutinesSwing)

    implementation(libs.compose.uiToolingPreview)
}

compose.desktop {
    application {
        mainClass = "com.yahyafati.poolprint.MainKt"

        buildTypes.release.proguard {
            // sshj, BouncyCastle and JNA load classes reflectively; shrinking them is not worth the risk for a personal app.
            isEnabled.set(false)
        }

        nativeDistributions {
            // macOS only for now (D-18); add Msi/Deb here if a Windows or Linux build is ever wanted.
            targetFormats(TargetFormat.Dmg)
            packageName = "Pool Print"
            // Numbers only on macOS (D-18): 1.0.0-rc.1 is packaged as 1.0.0; the app shows the full name.
            packageVersion = appVersion.macPackageVersion
            // From suggestRuntimeModules: the jlink runtime otherwise lacks what sshj and PDFBox reach for.
            modules("java.instrument", "java.naming", "java.security.jgss", "java.sql", "jdk.unsupported")
            description = "Print PDFs on the Uni Freiburg TF pool printers"
            vendor = "Yahya Fati"

            macOS {
                bundleID = "com.yahyafati.poolprint"
                dockName = "Pool Print"
                iconFile.set(project.file("icons/PoolPrint.icns"))
                appCategory = "public.app-category.utilities"
                minimumSystemVersion = "12.0"

                // Lets Finder offer "Open With → Pool Print" for PDFs. Rank "Alternate" keeps Preview as the
                // default viewer; the handler itself is IncomingPdfs.installOpenFileHandler().
                infoPlist {
                    extraKeysRawXml = """
                        <key>CFBundleDocumentTypes</key>
                        <array>
                          <dict>
                            <key>CFBundleTypeName</key>
                            <string>PDF Document</string>
                            <key>CFBundleTypeRole</key>
                            <string>Viewer</string>
                            <key>LSHandlerRank</key>
                            <string>Alternate</string>
                            <key>LSItemContentTypes</key>
                            <array>
                              <string>com.adobe.pdf</string>
                            </array>
                          </dict>
                        </array>
                    """.trimIndent()
                }
            }
        }
    }
}
